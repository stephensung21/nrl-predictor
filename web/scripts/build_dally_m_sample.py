"""Builds web/lib/sample-dally-m.ts for the community Dally M page (/dally-m).

Run from the repo root:  python web/scripts/build_dally_m_sample.py

Real players, made-up votes: pipeline/players.py's round_players for 2026 rounds 1-9 (who really took
the field, with nrl.com photo links), and votes by the sample tippers (lib/sample.ts) for rounds 1-8,
drawn at random weighted towards each round's highest fantasy scorers so the leaderboard looks like a
real one. At the sample's "tips open" instant (Tue 5 May 2026) round 9 is open: three tippers have
voted, but not "you", so the page and the tipping nudge show the open state.
"""

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "pipeline"))
import players  # noqa: E402  (puts src/ on the path too, through common)
from common import load_matches  # noqa: E402

OUT = ROOT / "web" / "lib" / "sample-dally-m.ts"
SEASON, ROUNDS, OPEN = 2026, range(1, 10), 9
TIPPERS = ["mick", "dazza", "sully", "jacko", "tom"]  # lib/sample.ts, without the Model
OPEN_VOTERS = 3

rng = np.random.default_rng(12)
matches = load_matches()
m = matches[(matches["season"] == SEASON)].copy()
m["kick"] = pd.to_datetime(m["start_time_utc"], utc=True)
stats = players.load_players()
fantasy = stats[stats["season"] == SEASON].set_index(["match_id", "player_id"])["fantasyPointsTotal"]
rp = players.tables(SEASON)["round_players"]
rp = rp[rp["round"].isin(ROUNDS)]


def closes(rnd):
    """As dally_m_closes: the first kickoff after the round's last regular-season game."""
    last = m.loc[(m["round"] == rnd) & ~m["is_final"].astype(str).str.lower().eq("true"), "kick"].max()
    later = m.loc[m["kick"] > last, "kick"]
    return (later.min() if len(later) else last + pd.Timedelta(days=7)).strftime("%Y-%m-%dT%H:%M:%S.000Z")


people = {int(r.player_id): {"name": r.player_name, "team": r.team, "image": None if pd.isna(r.head_image) else r.head_image}
          for r in rp.sort_values("round").itertuples()}
rounds, votes = [], []
for rnd in ROUNDS:
    here = rp[rp["round"] == rnd]
    rounds.append({"round": rnd, "closes": closes(rnd), "players": [[int(r.player_id), r.position, str(int(r.match_id))]
                                                                      for r in here.sort_values("player_name").itertuples()]})
    if rnd == OPEN:
        continue
    fp = np.array([fantasy.get((r.match_id, r.player_id), 0) for r in here.itertuples()], dtype=float)
    weight = np.clip(fp - 40, 1, None) ** 3  # strongly towards the round's standouts
    ids = here["player_id"].astype(int).to_numpy()
    for who in TIPPERS:
        pick = rng.choice(ids, size=3, replace=False, p=weight / weight.sum())
        votes += [{"userId": who, "round": rnd, "votes": v, "playerId": int(p)} for v, p in zip((3, 2, 1), pick)]

body = json.dumps({"people": people, "rounds": rounds, "votes": votes}, separators=(",", ":"))
OUT.write_text(
    "// GENERATED by web/scripts/build_dally_m_sample.py. Do not edit by hand.\n"
    "// Real 2026 players for rounds 1-9 (who took the field); the votes are made up for the sample tippers.\n\n"
    "type Raw = {\n"
    "  people: Record<string, { name: string; team: string; image: string | null }>;\n"
    "  rounds: { round: number; closes: string; players: [number, string, string][] }[];\n"
    "  votes: { userId: string; round: number; votes: 1 | 2 | 3; playerId: number }[];\n"
    "};\n\n"
    f"export const SAMPLE_DALLY_M_SEASON = {SEASON};\n"
    f"export const SAMPLE_DALLY_M_OPEN = {OPEN};\n"
    f"/** Tippers who have voted in the open round (not including you). */\n"
    f"export const SAMPLE_DALLY_M_OPEN_VOTERS = {OPEN_VOTERS};\n\n"
    "// Parsed from a string: as object literals this much data is slow for TypeScript to check.\n"
    f"export const SAMPLE_DALLY_M_RAW: Raw = JSON.parse({json.dumps(body)});\n",
    encoding="utf-8", newline="\n")
print(f"wrote {OUT.relative_to(ROOT)}: {len(people)} players, {len(rounds)} rounds, {len(votes)} votes, "
      f"{OUT.stat().st_size // 1024} KB")
