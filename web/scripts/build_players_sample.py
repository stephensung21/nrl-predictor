"""Builds web/lib/sample-players.ts for the players page (/players).

Run from the repo root:  python web/scripts/build_players_sample.py

Real data only: pipeline/players.py's tables (each player's season of stats, fantasy rating and the Model's impact)
for the last two finished seasons, cut to the most-used players each season so the sample stays small.
"""

import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "pipeline"))
import players  # noqa: E402  (puts src/ on the path too, through common)

OUT = ROOT / "web" / "lib" / "sample-players.ts"
SEASONS = [2026, 2025]
PER_SEASON = 160  # players kept per season, by minutes

rows = []
for season in SEASONS:
    t = players.tables(season)
    s = t["player_seasons"].merge(t["player_ratings"].drop(columns="as_of"), on=["season", "player_id"], how="left")
    s = s.nlargest(PER_SEASON, "minutes")
    for r in s.itertuples(index=False):
        d = r._asdict()
        rows.append({
            "season": int(d["season"]), "id": int(d["player_id"]), "name": d["player_name"], "team": d["team"],
            "position": d["position"], "games": int(d["games"]),
            "image": None if pd.isna(d["head_image"]) else d["head_image"],
            "fantasyRating": None if pd.isna(d["fantasy_rating"]) else round(float(d["fantasy_rating"]), 4),
            **{k: (None if pd.isna(d[c]) else round(float(d[c]), 4))
               for k, c in (("impact", "rating"), ("attack", "attack"), ("defence", "defence"))},
            "stats": {k: (round(float(d[k]), 1) if k == "fantasy_points" else int(d[k])) for k in players.TOTALS},
        })

body = json.dumps(rows, separators=(",", ":"))
OUT.write_text(
    "// GENERATED by web/scripts/build_players_sample.py. Do not edit by hand.\n"
    "// Real data only: pipeline/players.py's tables for 2025 and 2026, the most-used players each season.\n\n"
    'import type { PlayerSeason } from "./players";\n\n'
    f"export const SAMPLE_PLAYER_SEASONS = {json.dumps(SEASONS)};\n\n"
    "// Parsed from a string: as object literals this much data is slow for TypeScript to check.\n"
    f"export const SAMPLE_PLAYERS: PlayerSeason[] = JSON.parse({json.dumps(body)});\n",
    encoding="utf-8", newline="\n")
print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} player seasons")
