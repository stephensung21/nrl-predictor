"""Builds web/lib/sample-drivers.ts: what drove each sample game's prediction (PLAN_WEB.md §7.1),
from the replayed 2026 rounds the sample pages show, so the match page's "What drove this" panel has
honest data until the pipeline publishes `record_drivers`.

Each round is re-predicted as of its Tuesday with the 2026 models (as the sample's predictions were)
and split up by src/explain.py; the groups must add up to the sample's predicted margin.

Run from the repo root (about a minute a round):  python web/scripts/build_drivers_sample.py
"""

import json
import sys
import warnings
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

import explain  # noqa: E402
import predict  # noqa: E402

OUT = ROOT / "web" / "lib" / "sample-drivers.ts"
ROUNDS = [3, 5, 10]  # the replays in web/scripts/build_sample.py
SEASON = 2026

warnings.filterwarnings("ignore")
bundle = predict.load_bundle(SEASON)
drivers = {}
for rnd in ROUNDS:
    fixtures, lists = predict.replay_round(SEASON, rnd)
    out, rows, _, _ = predict.predict_fixtures(fixtures, lists, bundle, keep_weather=True)
    d = explain.explain(bundle, rows, predict.variant_of(out), out.set_index("match_id")["home_win_prob"])
    groups = explain.by_group(d)
    variant = dict(zip(d["match_id"], d["variant"]))

    # The sample shows the replay's saved predictions: the drivers must explain those exact margins.
    saved = pd.read_csv(ROOT / f"reports/predictions/{SEASON}_round{rnd}_replay.csv").set_index("match_id")["margin"]
    for mid, g in groups.groupby("match_id"):
        total = g["margin_pts"].sum()
        assert abs(total - saved.loc[mid]) < 1e-6, f"round {rnd} match {mid}: drivers {total} != margin {saved.loc[mid]}"
        drivers[str(mid)] = {
            "variant": variant[mid],
            "groups": [{"group": r.group, "points": round(float(r.margin_pts), 3)}
                       for r in g.itertuples() if r.group != "calibration"],
        }
    print(f"round {rnd}: {g['match_id'].nunique() if len(g) else 0} games checked", file=sys.stderr)

OUT.write_text(
    "// GENERATED by web/scripts/build_drivers_sample.py. Do not edit by hand.\n"
    "// What drove each sample game's prediction (2026 rounds 3, 5 and 10, replayed as of Tuesday), in\n"
    "// points of predicted home margin: src/explain.py's groups, adding up to the sample's margin.\n\n"
    'import type { Drivers } from "./types";\n\n'
    f"export const SAMPLE_DRIVERS: Record<string, Drivers> = {json.dumps(drivers, indent=2)};\n",
    encoding="utf-8",
)
print(f"wrote {OUT.relative_to(ROOT)} ({len(drivers)} games)")
